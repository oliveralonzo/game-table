from typing import Protocol
from game_table.tournament.tournament import Tournament


class TournamentRepository(Protocol):
    def create(self, tournament: Tournament) -> bool:
        """Persist only if creator is still a current group admin or owner."""
        ...

    def delete(self, tournament_id: str, account_id: str) -> bool: ...

    def list_for_group(self, group_id: str, account_id: str) -> list[Tournament]: ...

    def get_by_id(self, tournament_id: str, account_id: str) -> Tournament | None: ...

    def attendance_for_group(self, group_id: str, account_id: str) -> dict: ...

    def set_attendance_intent(self, tournament_id: str, account_id: str, attending: str | bool, updated_at: int) -> bool: ...

    def attendance_roster(self, tournament_id: str, account_id: str) -> list[dict]: ...
